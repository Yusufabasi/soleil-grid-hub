"""The local compose stack answering through the balancer (slice 00).

These tests need the stack that ``make up`` starts, so they are marked ``integration`` and are
run by ``make verify`` after it. They assert what the balancer is responsible for — every pool
reachable through its own route, one request id per request, health visible per backend — and
that nothing the stack carried in its environment ends up in its logs.
"""

from __future__ import annotations

import csv
import io
import json
import re
import subprocess
import time
import urllib.error
import urllib.request
import uuid
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
BALANCER = "http://localhost:8080"
STATS_CSV = "http://localhost:8404/stats;csv"
COMPOSE = ("docker", "compose", "--env-file", ".env", "-f", "infra/docker/compose.yaml")

# The five pools of docs/09 1.4, as the balancer names them.
POOLS = {"be_web", "be_api", "be_stream", "be_webhooks", "be_telemetry"}

# A value in .env that is named like a credential is either a documented dev placeholder
# (identical to .env.example, e.g. `dev`) or a real secret; only the second kind must never be
# in a log, and the second kind is also long enough to recognise.
SECRET_NAME = re.compile(r"SECRET|PASSWORD|_PW$|TOKEN|API_KEY|PRIVATE|CREDENTIAL|PEPPER|SALT")
MIN_SECRET_LENGTH = 8


def get(path: str, headers: dict[str, str] | None = None) -> tuple[int, dict[str, str], bytes]:
    """GET one path through the balancer; returns status, headers and raw body."""
    request = urllib.request.Request(BALANCER + path, headers=headers or {}, method="GET")
    try:
        with urllib.request.urlopen(request, timeout=10) as response:  # noqa: S310
            return response.status, dict(response.headers), response.read()
    except urllib.error.HTTPError as error:  # a 503 is an answer, not a transport failure
        return error.code, dict(error.headers), error.read()


def wait_for_balancer(timeout: float = 20.0) -> None:
    """Wait until the balancer routes again.

    HAProxy takes a server out after two failed checks and puts it back after three passes
    (``fall 2``/``rise 3``), so a freshly started pool answers 503 for a few seconds while
    ``docker compose up --wait`` is already satisfied by the container's own healthcheck.
    """
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            status, _, _ = get("/api/v1/health/live")
        except urllib.error.URLError:  # the balancer is not listening yet
            status = 0
        if status == 200:
            return
        time.sleep(0.5)
    raise AssertionError("the balancer never answered 200 on /api/v1/health/live")


def header(headers: dict[str, str], name: str) -> str | None:
    """One response header, case-insensitively (urllib preserves the server's spelling)."""
    for key, value in headers.items():
        if key.lower() == name.lower():
            return value
    return None


def compose(*arguments: str) -> subprocess.CompletedProcess[str]:
    """Run one docker compose command from the repository root."""
    return subprocess.run(  # noqa: S603 - fixed argv, no shell
        [*COMPOSE, *arguments],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


def env_file() -> dict[str, str]:
    values: dict[str, str] = {}
    for line in (ROOT / ".env").read_text().splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        name, _, value = stripped.partition("=")
        values[name.strip()] = value.strip()
    return values


@pytest.mark.integration
@pytest.mark.tc("TC-NFR-14-1")
def test_health_through_the_balancer_for_every_pool():
    wait_for_balancer()

    status, headers, body = get("/api/v1/health/live")
    assert status == 200, body
    assert json.loads(body)["data"]["status"] == "ok"
    # docs/03 7.3: the client always gets an id back, generated by the balancer.
    request_id = header(headers, "X-Request-Id")
    assert request_id is not None, headers
    uuid.UUID(request_id)

    status, _, body = get("/api/v1/health/ready")
    assert status == 200, body
    document = json.loads(body)["data"]
    assert document["status"] in {"ok", "degraded"}
    checks = {check["name"]: check["status"] for check in document["checks"]}
    assert checks["postgres"] == "ok", document

    # be_web: the stub answers where the Next.js shell will.
    status, _, body = get("/")
    assert status == 200, body
    assert b"hub-web stub" in body

    # be_webhooks: the ingest process itself, reached inside its own container, so the pool's
    # health check is proved from the same place the balancer probes it.
    probe = compose(
        "exec",
        "-T",
        "hub-ingest-webhooks",
        "python",
        "-c",
        "import urllib.request as u; print(u.urlopen("
        "'http://127.0.0.1:8000/api/v1/health/ready', timeout=2).status)",
    )
    assert probe.returncode == 0, probe.stderr
    assert probe.stdout.strip() == "200", probe.stdout


@pytest.mark.integration
@pytest.mark.tc("TC-NFR-09-1")
def test_request_id_is_the_balancer_own_even_with_traceparent():
    trace_id = uuid.uuid4().hex
    incoming = {"traceparent": f"00-{trace_id}-0000000000000001-01"}

    _, first, _ = get("/api/v1/health/live", incoming)
    _, second, _ = get("/api/v1/health/live", incoming)

    first_id = header(first, "X-Request-Id")
    second_id = header(second, "X-Request-Id")
    assert first_id and second_id
    uuid.UUID(first_id)
    uuid.UUID(second_id)
    # The trace context identifies the trace, the request id identifies the request: the
    # balancer must not adopt the caller's trace id as the request id, and two requests must
    # never share one.
    assert first_id.replace("-", "") != trace_id
    assert first_id != second_id


@pytest.mark.integration
@pytest.mark.tc("TC-NFR-01-1")
def test_stats_page_lists_all_five_pools_up():
    wait_for_balancer()

    with urllib.request.urlopen(STATS_CSV, timeout=10) as response:  # noqa: S310
        text = response.read().decode("utf-8")

    rows = list(csv.DictReader(io.StringIO(text.lstrip("# "))))

    # A backend row reports UP when at least one of its servers is UP; the per-server rows
    # report what the readiness probe saw.
    up = {
        row["pxname"]
        for row in rows
        if row["svname"] == "BACKEND" and row["status"] == "UP" and row["pxname"] in POOLS
    }
    assert up == POOLS, sorted(POOLS - up)

    servers = {
        (row["pxname"], row["svname"], row["status"])
        for row in rows
        if row["pxname"] in POOLS and row["svname"] not in {"FRONTEND", "BACKEND"}
    }
    assert servers, "no server rows in the stats page"

    # Each pool has at least one server the health check accepts. `server-template ... 2`
    # reserves a second slot for scale-out, and a slot with no container behind it reports
    # MAINT (resolution) — a placeholder, not a failing server.
    for pool in POOLS:
        statuses = [status for name, _, status in servers if name == pool]
        assert "UP" in statuses, (pool, statuses)
    assert all(
        status == "UP" or status.startswith("MAINT (resolution)") for _, _, status in servers
    ), sorted(servers)


@pytest.mark.integration
@pytest.mark.tc("TC-NFR-09-1")
def test_request_leaves_one_json_line_with_its_request_id():
    wait_for_balancer()

    status, headers, _ = get("/api/v1/health/live")
    assert status == 200
    request_id = header(headers, "X-Request-Id")
    assert request_id, headers

    line: str | None = None
    deadline = time.monotonic() + 10
    while line is None and time.monotonic() < deadline:
        logs = compose("logs", "--no-color", "--no-log-prefix", "--since", "1m", "hub-api")
        assert logs.returncode == 0, logs.stderr
        line = next((item for item in logs.stdout.splitlines() if request_id in item), None)
        if line is None:
            time.sleep(0.5)
    assert line is not None, "no log line carries the request id"

    record = json.loads(line)
    assert record["event"] == "request.completed"
    assert record["service"] == "hub-api"
    assert record["request_id"] == request_id
    assert record["status"] == 200
    assert record["path"] == "/api/v1/health/live"
    # D-18: the query string never reaches a log sink, so the path is what is recorded.
    assert "?" not in record["path"]
    # The line is joined to the trace by the same 32 hexadecimal digits the collector has.
    assert re.fullmatch(r"[0-9a-f]{32}", record["trace_id"] or ""), record


@pytest.mark.integration
@pytest.mark.tc("TC-NFR-06-6")
def test_no_secret_in_container_logs():
    logs = compose("logs", "--no-color")
    assert logs.returncode == 0, logs.stderr
    output = logs.stdout
    # An empty log is not a clean log: it means no container ran, and nothing was proved.
    assert output.strip(), "no container logs: is the stack up (make up)?"

    documented = env_file()
    example = {
        name: value
        for name, value in (
            line.strip().partition("=")[::2]
            for line in (ROOT / ".env.example").read_text().splitlines()
            if line.strip() and not line.strip().startswith("#") and "=" in line
        )
    }
    secrets = {
        name: value
        for name, value in documented.items()
        if SECRET_NAME.search(name) and len(value) >= MIN_SECRET_LENGTH and value != example.get(name)
    }
    for name, value in secrets.items():
        assert value not in output, f"{name} appears in the stack's logs"

    # No credential or session header may be logged either (docs/09 8.6).
    assert "Authorization" not in output
    assert "Cookie:" not in output
