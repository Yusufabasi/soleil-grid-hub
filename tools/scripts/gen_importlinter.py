#!/usr/bin/env python3
"""Generate ``backend/.importlinter`` from the dependency rules in docs/03.

The contracts are not hand-maintained: the allowed directions of docs/03 section 3.1 are a
matrix, and the per-pair ``public-surface`` contracts are exactly its forbidden cells. Keeping
them in one table means a changed direction is one line here, and ``--check`` (run by the
architecture tests and CI) fails when the committed file and the table disagree.

Usage:

    python tools/scripts/gen_importlinter.py          # rewrite backend/.importlinter
    python tools/scripts/gen_importlinter.py --check  # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIG_PATH = REPO_ROOT / "backend" / ".importlinter"

# The twelve business modules, in the order docs/03 section 3 lists them. ``shared`` (the
# kernel) and the technical packages (hubdb, settings, urls) are not "modules".
MODULES = (
    "identity",
    "customers",
    "payments",
    "ledger",
    "meters",
    "telemetry",
    "support",
    "ai_gateway",
    "analytics",
    "notifications",
    "reconciliation",
    "admin",
)

# docs/03 section 3.1: for each module, the modules whose contracts/events it may import.
# Everything not listed is a forbidden direction, including the module itself.
ALLOWED: dict[str, tuple[str, ...]] = {
    "identity": ("shared",),
    "customers": ("shared", "identity"),
    "payments": ("shared", "identity", "customers", "ledger"),
    "ledger": ("shared",),
    "meters": ("shared", "identity", "customers", "ledger"),
    "telemetry": ("shared", "identity", "meters"),
    "support": ("shared", "identity", "customers", "ai_gateway", "notifications"),
    "ai_gateway": ("shared",),
    "analytics": ("shared", "identity", "ai_gateway"),
    "notifications": ("shared", "identity", "customers"),
    # reconciliation calls PaymentService and TokenService (D-15), so it sees meters too.
    "reconciliation": ("shared", "identity", "payments", "ledger", "meters"),
    "admin": ("shared", "identity"),
}

# docs/03 3.3: these packages are wiring, not layers, and are excluded from public-surface.
EXCLUDED_FROM_PUBLIC_SURFACE = (
    "hub.bootstrap",
    "hub.urls",
    "hub.settings",
    "hub.wsgi_api",
    "hub.wsgi_ingest",
    "hub.asgi_stream",
)

HEADER = """\
# Generated by tools/scripts/gen_importlinter.py from docs/03-code-architecture.md 3.3 and
# the allowed-direction matrix of section 3.1. Do not edit by hand: edit the generator (or
# the document) and run `python tools/scripts/gen_importlinter.py`.
#
# Django apps are ordinary Python packages, so these are the same contracts a plain Python
# service would have, with `hub.` names.

[importlinter]
root_package = hub
include_external_packages = True
"""

STATIC_CONTRACTS = """
# 1. Layers inside every app. apps.py and the models shims sit outside the layers by design.
[importlinter:contract:layers]
name = Layers inside each module
type = layers
# Relative to each container: import-linter prefixes the container, so `api` is
# `<container>.api` with the contract's depth unchanged.
layers =
    api
    application
    domain
containers =
    hub.identity
    hub.customers
    hub.payments
    hub.ledger
    hub.meters
    hub.telemetry
    hub.support
    hub.ai_gateway
    hub.analytics
    hub.notifications
    hub.reconciliation
    hub.admin

[importlinter:contract:domain-pure]
name = Domain has no frameworks
type = forbidden
source_modules =
    hub.*.domain
forbidden_modules =
    django
    rest_framework
    psycopg
    httpx
    redis
    anthropic
    boto3
    pydantic
    hub.*.infrastructure
    hub.*.api
    hub.*.application

[importlinter:contract:application-no-outer]
name = Application does not depend on outer layers or frameworks
type = forbidden
source_modules =
    hub.*.application
forbidden_modules =
    hub.*.infrastructure
    hub.*.api
    django
    rest_framework
    psycopg
    anthropic
    pydantic
"""

MODELS_PRIVATE = """
# 2. api, application and domain never import models, not even their own; repositories do.
[importlinter:contract:models-private]
name = Models are private to their app
type = forbidden
source_modules =
    hub.*.api
    hub.*.application
    hub.*.domain
forbidden_modules =
    hub.*.models
    hub.*.infrastructure.models
"""

MODULE_DAG = """
# 3. Module direction (docs/03 3.1) over the app DAG. Siblings on one line are independent;
# reconciliation sits above payments and meters because it calls PaymentService and
# TokenService (D-15). No module imports admin.
[importlinter:contract:module-dag]
name = Module dependency direction
type = layers
layers =
    hub.admin | hub.analytics | hub.support | hub.telemetry | hub.notifications
    hub.reconciliation
    hub.payments | hub.meters
    hub.customers | hub.ai_gateway
    hub.ledger
    hub.identity
    hub.shared

# 4. SDK containment: the AI SDK is reached through one adapter, nowhere else.
[importlinter:contract:anthropic-only-in-gateway]
name = Only the ai_gateway adapter imports the AI SDK
type = forbidden
source_modules =
    hub
forbidden_modules =
    anthropic
ignore_imports =
    hub.ai_gateway.infrastructure.anthropic_client -> anthropic
# The adapter lands with the ai_gateway slice; until then the ignore matches nothing.
unmatched_ignore_imports_alerting = warn

[importlinter:contract:pydantic-only-in-gateway]
name = Only the ai_gateway may use pydantic
type = forbidden
source_modules =
    hub
forbidden_modules =
    pydantic
ignore_imports =
    hub.ai_gateway.** -> pydantic
unmatched_ignore_imports_alerting = warn

# `django.contrib.admin` cannot be a forbidden module here: import-linter rejects subpackages
# of external packages, and `include_external_packages` is required for the SDK contracts
# above. The ban is enforced instead by the AST scan in
# `tests/architecture/test_importlinter.py::test_no_module_imports_django_admin`, which also
# covers strings that never become an import graph edge.
"""

WIRING_ONLY = """
# 5. Wiring and settings are not importable from business layers; they read
# django.conf.settings instead. The kernel's own health view needs the container (the clock
# and the id generator are process-wide ports), so that one edge is exempt and nothing else.
[importlinter:contract:wiring-only]
name = Business layers never import the wiring
type = forbidden
source_modules =
    hub.*.api
    hub.*.application
    hub.*.domain
    hub.*.infrastructure
forbidden_modules =
    hub.bootstrap
    hub.settings
    hub.urls
    hub.wsgi_api
    hub.wsgi_ingest
    hub.asgi_stream
ignore_imports =
    hub.shared.api.health -> hub.bootstrap

# 6. The kernel depends on nothing above it: no business vocabulary, no business module.
[importlinter:contract:shared-is-kernel]
name = hub.shared imports no business module
type = forbidden
source_modules =
    hub.shared
forbidden_modules =
    hub.identity
    hub.customers
    hub.payments
    hub.ledger
    hub.meters
    hub.telemetry
    hub.support
    hub.ai_gateway
    hub.analytics
    hub.notifications
    hub.reconciliation
    hub.admin
"""


def public_surface_contract(source: str, target: str) -> str:
    """One forbidden contract for a cell of the matrix that is not allowed.

    A module's own ``contracts`` and ``events`` are its public surface, and the matrix is
    written in terms of them: every module may import another's. Those modules necessarily
    name their own internals (``identity.contracts`` holds the ``Principal`` the domain
    defines), so the edges below are ignored. Without them the contract forbids the very
    vocabulary it is named after, and a module that follows the rule fails it.
    """
    surfaces = ("contracts", "events")
    inner = ("api", "application", "domain", "infrastructure", "models")
    # The package itself and everything under it: `identity.contracts` names
    # `identity.domain.principal`, and the bare module name does not match that edge.
    ignores = "\n".join(
        f"    hub.{target}.{surface} -> hub.{target}.{layer}{suffix}"
        for surface in surfaces
        for layer in inner
        for suffix in ("", ".**")
    )
    return f"""
[importlinter:contract:public-surface-{source}-{target}]
name = {source} sees only {target} contracts and events
type = forbidden
source_modules =
    hub.{source}
forbidden_modules =
    hub.{target}.api
    hub.{target}.application
    hub.{target}.domain
    hub.{target}.infrastructure
    hub.{target}.models
allow_indirect_imports = False
ignore_imports =
{ignores}
unmatched_ignore_imports_alerting = warn
"""


def render() -> str:
    """The whole ``.importlinter`` file as text."""
    parts = [HEADER, STATIC_CONTRACTS]
    for source in MODULES:
        for target in MODULES:
            if target == source or target in ALLOWED[source]:
                continue
            parts.append(public_surface_contract(source, target))
    parts.extend([MODELS_PRIVATE, MODULE_DAG, WIRING_ONLY])
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when backend/.importlinter differs from the generated content",
    )
    args = parser.parse_args(argv)
    expected = render()

    if args.check:
        actual = CONFIG_PATH.read_text(encoding="utf-8") if CONFIG_PATH.exists() else ""
        if actual == expected:
            print(f"{CONFIG_PATH.relative_to(REPO_ROOT)} is up to date")
            return 0
        diff = difflib.unified_diff(
            actual.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=str(CONFIG_PATH.relative_to(REPO_ROOT)),
            tofile="generated",
        )
        sys.stdout.writelines(diff)
        print("run `python tools/scripts/gen_importlinter.py` to regenerate", file=sys.stderr)
        return 1

    CONFIG_PATH.write_text(expected, encoding="utf-8")
    print(f"wrote {CONFIG_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
